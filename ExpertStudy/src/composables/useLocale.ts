type MessageKey = keyof typeof zh

function initialLocale(): StudyLocale {
  if (typeof window === "undefined") return "zh"
  const stored = window.localStorage.getItem(LOCALE_STORAGE_KEY)
  if (stored === "zh" || stored === "en") return stored
  return window.navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en"
}

const locale = ref<StudyLocale>(initialLocale())

watch(
  locale,
  (value) => {
    if (typeof window !== "undefined") {
      window.localStorage.setItem(LOCALE_STORAGE_KEY, value)
      document.documentElement.lang = value === "zh" ? "zh-CN" : "en"
    }
  },
  { immediate: true },
)

function interpolate(message: string, params?: Record<string, string | number>): string {
  if (!params) return message
  return Object.entries(params).reduce(
    (result, [key, value]) => result.split(`{${key}}`).join(String(value)),
    message,
  )
}

export const languageOptions = [
  { label: "中文", value: "zh" },
  { label: "English", value: "en" },
]

export function useLocale() {
  function t(key: MessageKey, params?: Record<string, string | number>): string {
    return interpolate((locale.value === "zh" ? zh : en)[key], params)
  }

  function pick<T>(zhValue: T, enValue: T): T {
    return locale.value === "zh" ? zhValue : enValue
  }

  return { locale, t, pick }
}
